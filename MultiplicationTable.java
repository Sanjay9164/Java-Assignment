import java.util.Scanner;
public class MultiplicationTable {
    public static void Main(string[] args){
        scanner sc = new Scanner(System.in);
        System.out.println("Enter a number: ");
        int num = Sc.nextInt();

        for(int i=1;i<=10;i++){
           system.out.println(num + "X" + i + "=" + (num-i));
        }

    }
}